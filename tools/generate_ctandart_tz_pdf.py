def para(text: str, style_name: str = "BodyDoc"):
    return Paragraph(ptext(text), STYLES[style_name])


def bullets(items: list[str]):
    return ListFlowable(
        [
            ListItem(Paragraph(ptext(item), STYLES["BulletDoc"]), leftIndent=8)
            for item in items
        ],
        bulletType="bullet",
        start="circle",
        leftIndent=12,
        bulletFontName="DocRegular",
        bulletFontSize=7,
        bulletColor=colors.HexColor("#2563eb"),
        spaceBefore=2,
        spaceAfter=6,
    )


def table(rows, widths=None, header=True, font_size=None):
    converted = []
    for r_i, row in enumerate(rows):
        converted_row = []
        for cell in row:
            style = STYLES["CellBold"] if header and r_i == 0 else STYLES["Cell"]
            converted_row.append(Paragraph(ptext(str(cell)), style))
        converted.append(converted_row)
    t = Table(converted, colWidths=widths, hAlign="LEFT", repeatRows=1 if header else 0)
    t.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8eef8") if header else colors.white),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#111827")),
                ("FONTNAME", (0, 0), (-1, -1), "DocRegular"),
                ("FONTSIZE", (0, 0), (-1, -1), font_size or 7.8),
                ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 5),
                ("RIGHTPADDING", (0, 0), (-1, -1), 5),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("ROWBACKGROUNDS", (0, 1 if header else 0), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
            ]
        )
    )
    return t


def section(story, title: str, body: list):
    story.append(Paragraph(ptext(title), STYLES["H1"]))
    for item in body:
        if isinstance(item, str):
            story.append(para(item))
        else:
            story.append(item)
    story.append(Spacer(1, 4))


def sub(story, title: str):
    story.append(Paragraph(ptext(title), STYLES["H2"]))


